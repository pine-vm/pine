namespace Pine.Core.CLI;

/// <summary>
/// Decimal SI multipliers for integer counts.
/// </summary>
public enum CountUnit
{
    /// <summary>No multiplier.</summary>
    None,

    /// <summary>One thousand.</summary>
    Kilo,

    /// <summary>One million.</summary>
    Mega,

    /// <summary>One billion.</summary>
    Giga,
}
